export function t(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let str = (dict[lang]?.[key] ?? en[key]) as string;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

export function getLanguageMeta(code: Lang): LanguageMeta {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0];
}

// Map language code to a human-readable name for AI prompts (e.g. complaint generation)
export function languageFullName(code: Lang): string {
  const meta = getLanguageMeta(code);
  return `${meta.name} (${meta.nativeName})`;
}

